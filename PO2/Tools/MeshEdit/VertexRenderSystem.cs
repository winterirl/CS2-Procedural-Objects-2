            return m_ProceduralObjectSystem.IsToolActive && (m_ProceduralObjectToolSystem.AxisPickingActive || m_ProceduralObjectToolSystem.Mode == ObjectToolMode.MeshEdit || m_ProceduralObjectToolSystem.Mode == ObjectToolMode.Texturing);
        }
