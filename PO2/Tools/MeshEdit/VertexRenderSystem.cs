        protected override void OnCreate()
        {
            base.OnCreate();

            m_GizmosSystem = World.GetOrCreateSystemManaged<GizmosSystem>();

            m_ProceduralObjectSystem = World.GetOrCreateSystemManaged<ProceduralObjectSystem>();

            m_ProceduralObjectToolSystem = World.GetOrCreateSystemManaged<ProceduralObjectToolSystem>();

            PrefabSystem prefabSystem = World.GetOrCreateSystemManaged<PrefabSystem>();
            EntityQuery overlaySettingsQuery = GetEntityQuery(ComponentType.ReadOnly<OverlayConfigurationData>());
            m_VertexMarkerRenderer = new VertexMarkerRenderer(prefabSystem, overlaySettingsQuery);
            m_XRayEdgeRenderer = new XRayEdgeRenderer(prefabSystem, overlaySettingsQuery, m_VertexMarkerRenderer?.SharedComputeShader);
            m_MeshGpu = new MeshEditGpuSession(m_ProceduralObjectToolSystem.MeshController, m_ProceduralObjectToolSystem, m_VertexMarkerRenderer);
            m_ProceduralObjectToolSystem.MeshController.MeshGpu = m_MeshGpu;

            m_BufferA = new NativeList<VertexMarkerRenderData>(16, Allocator.Persistent);

            m_BufferB = new NativeList<VertexMarkerRenderData>(16, Allocator.Persistent);

            m_ActiveBufferIndex = 0;

            m_LoopPreviewBufferA = new NativeList<LoopCutPreviewLineRenderData>(16, Allocator.Persistent);
            m_LoopPreviewBufferB = new NativeList<LoopCutPreviewLineRenderData>(16, Allocator.Persistent);
            m_ActiveLoopPreviewBufferIndex = 0;

            m_EdgeBufferA = new NativeList<StructuralEdgeRenderData>(16, Allocator.Persistent);
            m_EdgeBufferB = new NativeList<StructuralEdgeRenderData>(16, Allocator.Persistent);
            m_ActiveEdgeBufferIndex = 0;
        }

        protected override void OnDestroy()
        {
            m_ProceduralObjectToolSystem.MeshController.MeshGpu = null;
            m_MeshGpu?.Dispose();
            m_MeshGpu = null;
            // The edge renderer borrows the compute shader owned by the vertex
            // renderer, so release its buffers/callback before unloading the
            // shared AssetBundle.
            if (m_XRayEdgeRenderer != null)
            {
                m_XRayEdgeRenderer.Dispose();
                m_XRayEdgeRenderer = null;
            }

            if (m_VertexMarkerRenderer != null)
            {
                m_VertexMarkerRenderer.Dispose();
                m_VertexMarkerRenderer = null;
            }

            m_BufferAReadHandle.Complete();
            m_BufferBReadHandle.Complete();
            m_LoopPreviewBufferAReadHandle.Complete();
            m_LoopPreviewBufferBReadHandle.Complete();
            m_EdgeBufferAReadHandle.Complete();
            m_EdgeBufferBReadHandle.Complete();

            if (m_BufferA.IsCreated)
            {
                m_BufferA.Dispose();
            }

            if (m_BufferB.IsCreated)
            {
                m_BufferB.Dispose();
            }

            if (m_LoopPreviewBufferA.IsCreated)
            {
                m_LoopPreviewBufferA.Dispose();
            }

            if (m_LoopPreviewBufferB.IsCreated)
            {
                m_LoopPreviewBufferB.Dispose();
            }

            if (m_EdgeBufferA.IsCreated)
            {
                m_EdgeBufferA.Dispose();
            }

            if (m_EdgeBufferB.IsCreated)
            {
                m_EdgeBufferB.Dispose();
            }

            base.OnDestroy();
        }

        protected override void OnUpdate()
        {
            m_MeshGpu?.Poll();
            if (!ShouldRender())
            {
                m_MeshGpu?.Stop();
                m_VertexMarkerRenderer?.SetActive(false);
                m_XRayEdgeRenderer?.SetActive(false);
                m_GpuMarkersActive = false;
                m_GpuXRayEdgesActive = false;
                return;
            }

            Camera camera = m_ProceduralObjectToolSystem.MeshEditCamera;
            if (camera == null)
            {
                m_VertexMarkerRenderer?.SetActive(false);
                m_XRayEdgeRenderer?.SetActive(false);
                m_GpuMarkersActive = false;
                m_GpuXRayEdgesActive = false;
                return;
            }

            if (!m_ProceduralObjectToolSystem.TryGetMeshEditFrameData(out VertexFrameData[] frameData, out int frameDataCount, out uint projectionVersion, out uint visualVersion))
            {
                m_VertexMarkerRenderer?.SetActive(false);
                m_XRayEdgeRenderer?.SetActive(false);
                m_GpuMarkersActive = false;
                m_GpuXRayEdgesActive = false;
                return;
            }

            m_MeshGpu?.RefreshVisuals();
            bool wasSharedGpu = m_GpuMeshActive;
            m_GpuMeshActive = m_ProceduralObjectToolSystem.MeshController.UsesGpuMarkers && m_MeshGpu.Active;
            if (wasSharedGpu != m_GpuMeshActive) m_HasSyncedMarkerData = false;

            // CPU preparation and the older renderers remain the resource-failure fallback.
            // Keep projection uploads separate from selection/hover state so camera movement
            // does not reclassify every vertex.
            bool faceSelectionActive = m_ProceduralObjectToolSystem.IsMeshEditFaceSelectionActive;
            uint faceSelectionVisualVersion = m_ProceduralObjectToolSystem.MeshEditFaceSelectionVisualVersion;

            bool shouldDrawVertexMarkers = !m_GpuMeshActive && !faceSelectionActive && m_ProceduralObjectToolSystem.MeshEditSelectionMode == MeshSelectionMode.Vertex && frameData != null && frameDataCount > 0;

            // GPU availability is optional. Missing bundle/shader resources
            // should degrade to the old GizmoBatcher rings, not kill mesh edit.
            bool shouldDrawGpuMarkers = shouldDrawVertexMarkers && m_VertexMarkerRenderer != null && m_VertexMarkerRenderer.IsAvailable;

            m_VertexMarkerRenderer?.SetVisibilityMode(m_ProceduralObjectToolSystem.MeshEditVisibility);

            bool shouldDrawLegacyMarkers = shouldDrawVertexMarkers && !shouldDrawGpuMarkers;

            if (shouldDrawGpuMarkers)
            {
                if (!m_GpuMarkersActive || !m_HasSyncedGpuMarkerData || projectionVersion != m_SyncedGpuMarkerProjectionVersion)
                {
                    m_VertexMarkerRenderer?.UpdateMarkers(frameData, frameDataCount);
                    m_SyncedGpuMarkerProjectionVersion = projectionVersion;
                    m_HasSyncedGpuMarkerData = true;
                }

                if (!m_GpuMarkersActive || !m_HasSyncedGpuMarkerVisualState || visualVersion != m_SyncedGpuMarkerVisualVersion)
                {
                    m_VertexMarkerRenderer?.UpdateVisualStates(frameData, frameDataCount, m_ProceduralObjectToolSystem);
                    m_SyncedGpuMarkerVisualVersion = visualVersion;
                    m_HasSyncedGpuMarkerVisualState = true;
                }

                m_GpuMarkersActive = true;
            }
            else
            {
                m_VertexMarkerRenderer?.SetActive(false);
                m_GpuMarkersActive = false;
            }

            bool hasEdgeFrameData = m_ProceduralObjectToolSystem.TryGetMeshEditEdgeFrameData(out EdgeFrameData[] edgeFrameData, out int edgeFrameDataCount, out uint edgeWorldVersion);

            bool shouldDrawGpuXRayEdges = !m_GpuMeshActive && !faceSelectionActive && m_ProceduralObjectToolSystem.MeshEditSelectionMode == MeshSelectionMode.Edge && m_ProceduralObjectToolSystem.MeshEditVisibility == MeshEditVisibilityMode.XRay && hasEdgeFrameData && edgeFrameData != null && edgeFrameDataCount > 0 && m_XRayEdgeRenderer != null && m_XRayEdgeRenderer.IsAvailable;

            bool wasDrawingGpuXRayEdges = m_GpuXRayEdgesActive;

            if (shouldDrawGpuXRayEdges)
            {
                bool edgeDataChanged = !m_GpuXRayEdgesActive || !m_HasSyncedGpuEdgeData || edgeWorldVersion != m_SyncedGpuEdgeWorldVersion;

                if (edgeDataChanged)
                {
                    shouldDrawGpuXRayEdges = m_XRayEdgeRenderer.UpdateEdges(edgeFrameData, edgeFrameDataCount);
                }

                if (shouldDrawGpuXRayEdges)
                {
                    int selectionVersion = m_ProceduralObjectToolSystem.MeshEditSelectionVersion;

                    if (edgeDataChanged || !m_HasSyncedGpuEdgeSelectionState || selectionVersion != m_SyncedGpuEdgeSelectionVersion)
                    {
                        m_XRayEdgeRenderer.UpdateSelectedEdges(m_ProceduralObjectToolSystem.GetMeshEditEdgeSelectionSnapshot());
                        m_SyncedGpuEdgeSelectionVersion = selectionVersion;
                        m_HasSyncedGpuEdgeSelectionState = true;
                    }

                    if (edgeDataChanged || !m_HasSyncedGpuEdgeVisualState || visualVersion != m_SyncedGpuEdgeVisualVersion)
                    {
                        StructuralEdgeRef? hoveredEdge = null;
                        if (m_ProceduralObjectToolSystem.TryGetMeshEditHoveredEdge(out StructuralEdgeRef hovered))
                        {
                            hoveredEdge = hovered;
                        }

                        m_XRayEdgeRenderer.UpdateHoveredEdge(hoveredEdge);
                        m_SyncedGpuEdgeVisualVersion = visualVersion;
                        m_HasSyncedGpuEdgeVisualState = true;
                    }

                    m_XRayEdgeRenderer.SetActive(true);
                    m_SyncedGpuEdgeWorldVersion = edgeWorldVersion;
                    m_HasSyncedGpuEdgeData = true;
                    m_GpuXRayEdgesActive = true;
                }
            }

            if (!shouldDrawGpuXRayEdges)
            {
                m_XRayEdgeRenderer?.SetActive(false);
                m_GpuXRayEdgesActive = false;
            }

            bool gpuXRayEdgePathChanged = wasDrawingGpuXRayEdges != m_GpuXRayEdgesActive;

            int selectedSurfacePartIndex = -1;
            int selectedSurfaceAreaId = -1;
            uint surfaceAreaMembershipVersion = 0;
            if (!faceSelectionActive && m_ProceduralObjectToolSystem.MeshEditSelectionMode == MeshSelectionMode.SurfaceArea && m_ProceduralObjectToolSystem.TryGetMeshVisualizationObject(out ProceduralObject surfaceEditedObject))
            {
                selectedSurfacePartIndex = m_ProceduralObjectSystem.SelectedPartIndex;
                selectedSurfaceAreaId = m_ProceduralObjectSystem.SelectedSurfaceAreaId;
                if (selectedSurfacePartIndex >= 0 && selectedSurfacePartIndex < surfaceEditedObject.Parts.Count)
                {
                    surfaceAreaMembershipVersion = surfaceEditedObject.Parts[selectedSurfacePartIndex].SurfaceAreaMembershipVersion;
                }
            }

            // Surface outlines also depend on active area membership, which is
            // not represented by the vertex projection/visual versions.
            bool surfaceOutlineStateChanged = selectedSurfacePartIndex != m_SyncedSurfacePartIndex || selectedSurfaceAreaId != m_SyncedSurfaceAreaId || surfaceAreaMembershipVersion != m_SyncedSurfaceAreaMembershipVersion;

            bool faceSelectionStateChanged = faceSelectionActive != m_SyncedFaceSelectionActive || faceSelectionVisualVersion != m_SyncedFaceSelectionVisualVersion;

            if (!m_HasSyncedMarkerData || projectionVersion != m_SyncedProjectionVersion || visualVersion != m_SyncedVisualVersion || surfaceOutlineStateChanged || faceSelectionStateChanged || gpuXRayEdgePathChanged)
            {
                SyncInactiveBuffer(frameData, frameDataCount);

                m_SyncedProjectionVersion = projectionVersion;
                m_SyncedVisualVersion = visualVersion;
                m_SyncedSurfacePartIndex = selectedSurfacePartIndex;
                m_SyncedSurfaceAreaId = selectedSurfaceAreaId;
                m_SyncedSurfaceAreaMembershipVersion = surfaceAreaMembershipVersion;
                m_SyncedFaceSelectionActive = faceSelectionActive;
                m_SyncedFaceSelectionVisualVersion = faceSelectionVisualVersion;
                m_HasSyncedMarkerData = true;
                SyncInactiveStructuralEdgeBuffer(m_GpuXRayEdgesActive || m_GpuMeshActive);
            }

            bool hasLoopCutPreview = m_ProceduralObjectToolSystem.TryGetMeshEditLoopCutPreview(out LoopCutPreviewLine[] loopCutPreviewLines, out int loopCutPreviewLineCount, out uint loopCutPreviewVersion);

            if (!m_HasSyncedLoopCutPreview || loopCutPreviewVersion != m_SyncedLoopCutPreviewVersion)
            {
                SyncInactiveLoopCutPreviewBuffer(hasLoopCutPreview ? loopCutPreviewLines : null, hasLoopCutPreview ? loopCutPreviewLineCount : 0);
                m_SyncedLoopCutPreviewVersion = loopCutPreviewVersion;
                m_HasSyncedLoopCutPreview = true;
            }

            NativeArray<VertexMarkerRenderData> markers = GetActiveBuffer().AsArray();
            NativeArray<LoopCutPreviewLineRenderData> loopPreview = GetActiveLoopCutPreviewBuffer().AsArray();
            NativeArray<StructuralEdgeRenderData> structuralEdges = GetActiveStructuralEdgeBuffer().AsArray();

            bool drawSlideEdge = m_ProceduralObjectToolSystem.TryGetMeshEditVertexSlideCandidateEdge(out Vector3 slideEdgeStart, out Vector3 slideEdgeEnd);

            if (markers.Length == 0 && loopPreview.Length == 0 && structuralEdges.Length == 0 && !drawSlideEdge)
            {
                return;
            }

            GizmoBatcher batcher = m_GizmosSystem.GetGizmosBatcher(out JobHandle dependencies);

            RenderMeshEditGizmosJob gizmoJob = new RenderMeshEditGizmosJob
            {
                Batcher = batcher,
                DrawSlideEdge = drawSlideEdge,
                SlideEdgeStart = slideEdgeStart,
                SlideEdgeEnd = slideEdgeEnd,
                LoopCutPreviewLines = loopPreview,
                StructuralEdges = structuralEdges,
            };

            RenderVertexMarkersJob markerJob = new RenderVertexMarkersJob
            {
                Batcher = batcher,
                CameraForward = camera.transform.forward,
                CameraRight = camera.transform.right,
                Markers = markers,
            };

            // Each active native buffer may still be read by last frame's job.
            // Carry those handles forward before scheduling another reader.
            JobHandle gizmoDependencies = JobHandle.CombineDependencies(Dependency, dependencies);

            gizmoDependencies = JobHandle.CombineDependencies(gizmoDependencies, GetActiveLoopCutPreviewReadHandle());

            gizmoDependencies = JobHandle.CombineDependencies(gizmoDependencies, GetActiveStructuralEdgeReadHandle());

            JobHandle gizmoRenderHandle = gizmoJob.Schedule(gizmoDependencies);

            JobHandle finalRenderHandle = gizmoRenderHandle;

            try
            {
                if (shouldDrawLegacyMarkers)
                {
                    JobHandle markerDependencies = JobHandle.CombineDependencies(gizmoRenderHandle, GetActiveReadHandle());
                    finalRenderHandle = markerJob.Schedule(markerDependencies);

                    SetActiveReadHandle(finalRenderHandle);
                } else
                {
                    // The primary GPU backend draws markers outside GizmoBatcher,
                    // so no fallback marker job reads this buffer on this frame.
                    SetActiveReadHandle(Dependency);
                }

                SetActiveLoopCutPreviewReadHandle(gizmoRenderHandle);
                SetActiveStructuralEdgeReadHandle(gizmoRenderHandle);
                m_GizmosSystem.AddGizmosBatcherWriter(finalRenderHandle);
                Dependency = finalRenderHandle;
            } catch
            {
                // Finish any scheduled readers before their buffers can be reused.
                finalRenderHandle.Complete();
                throw;
            }
        }

        private void SyncInactiveBuffer(VertexFrameData[] frameData, int frameDataCount)
        {
            int targetIndex = m_ActiveBufferIndex == 0 ? 1 : 0;
            JobHandle targetReadHandle = targetIndex == 0 ? m_BufferAReadHandle : m_BufferBReadHandle;

            // Never rewrite the active buffer. Wait for the inactive one's last
            // reader, fill it, then flip the index.
            targetReadHandle.Complete();

            if (targetIndex == 0)
            {
                FillBuffer(ref m_BufferA, frameData, frameDataCount);
            }
            else
            {
                FillBuffer(ref m_BufferB, frameData, frameDataCount);
            }

            m_ActiveBufferIndex = targetIndex;
        }

        private void FillBuffer(ref NativeList<VertexMarkerRenderData> buffer, VertexFrameData[] frameData, int frameDataCount)
        {
            if (m_ProceduralObjectToolSystem.MeshEditSelectionMode != MeshSelectionMode.Vertex || m_ProceduralObjectToolSystem.IsMeshEditFaceSelectionActive)
            {
                buffer.Clear();
                return;
            }

            buffer.Clear();
            if (buffer.Capacity < frameDataCount)
            {
                buffer.Capacity = frameDataCount;
            }

            // The fallback path physically omits hidden markers. The GPU path
            // keeps stable indices and zeroes their radii instead.
            bool solidMode = m_ProceduralObjectToolSystem.MeshEditVisibility == MeshEditVisibilityMode.Solid;

            for (int i = 0; i < frameDataCount; i++)
            {
                VertexFrameData frame = frameData[i];
                if (solidMode && !frame.SolidVisible)
                {
                    continue;
                }

                VertexMarkerVisualState visualState = VertexMarkerVisualStateUtility.GetState(m_ProceduralObjectToolSystem, frame.Vertex);

                Color color = VertexMarkerVisualStateUtility.GetColor(visualState);

                buffer.Add(new VertexMarkerRenderData
                {
                    Position = frame.WorldPosition,
                    Radius = frame.MarkerRadius,
                    Color = new float4(color.r, color.g, color.b, color.a),
                });
            }
        }

        private void SyncInactiveLoopCutPreviewBuffer(LoopCutPreviewLine[] previewLines, int previewLineCount)
        {
            int targetIndex = m_ActiveLoopPreviewBufferIndex == 0 ? 1 : 0;
            JobHandle targetReadHandle = targetIndex == 0 ? m_LoopPreviewBufferAReadHandle : m_LoopPreviewBufferBReadHandle;

            targetReadHandle.Complete();

            if (targetIndex == 0)
            {
                FillLoopCutPreviewBuffer(ref m_LoopPreviewBufferA, previewLines, previewLineCount);
            }
            else
            {
                FillLoopCutPreviewBuffer(ref m_LoopPreviewBufferB, previewLines, previewLineCount);
            }

            m_ActiveLoopPreviewBufferIndex = targetIndex;
        }

        private static void FillLoopCutPreviewBuffer(ref NativeList<LoopCutPreviewLineRenderData> buffer, LoopCutPreviewLine[] previewLines, int previewLineCount)
        {
            int count = previewLines != null ? Mathf.Min(previewLineCount, previewLines.Length) : 0;

            buffer.ResizeUninitialized(count);

            for (int i = 0; i < count; i++)
            {
                LoopCutPreviewLine source = previewLines[i];
                Color color = source.IsTargetEdge ? s_LoopCutTargetEdgeColor : s_LoopCutPreviewColor;

                buffer[i] = new LoopCutPreviewLineRenderData
                {
                    Start = source.Start,
                    End = source.End,
                    Color = new float4(color.r, color.g, color.b, color.a),
                };
            }
        }

        private NativeList<LoopCutPreviewLineRenderData> GetActiveLoopCutPreviewBuffer()
        {
            return m_ActiveLoopPreviewBufferIndex == 0 ? m_LoopPreviewBufferA : m_LoopPreviewBufferB;
        }

        private JobHandle GetActiveLoopCutPreviewReadHandle()
        {
            return m_ActiveLoopPreviewBufferIndex == 0 ? m_LoopPreviewBufferAReadHandle : m_LoopPreviewBufferBReadHandle;
        }

        private void SetActiveLoopCutPreviewReadHandle(JobHandle handle)
        {
            if (m_ActiveLoopPreviewBufferIndex == 0)
            {
                m_LoopPreviewBufferAReadHandle = handle;
            }
            else
            {
                m_LoopPreviewBufferBReadHandle = handle;
            }
        }

        private void SyncInactiveStructuralEdgeBuffer(bool suppressGpuEdgeWire)
        {
            int targetIndex = m_ActiveEdgeBufferIndex == 0 ? 1 : 0;
            JobHandle targetReadHandle = targetIndex == 0 ? m_EdgeBufferAReadHandle : m_EdgeBufferBReadHandle;

            targetReadHandle.Complete();

            if (targetIndex == 0)
            {
                FillStructuralEdgeBuffer(ref m_EdgeBufferA, suppressGpuEdgeWire);
            }
            else
            {
                FillStructuralEdgeBuffer(ref m_EdgeBufferB, suppressGpuEdgeWire);
            }

            m_ActiveEdgeBufferIndex = targetIndex;
        }

        private void FillStructuralEdgeBuffer(ref NativeList<StructuralEdgeRenderData> buffer, bool suppressGpuEdgeWire)
        {
            buffer.Clear();

            if (!m_ProceduralObjectToolSystem.TryGetMeshVisualizationObject(out ProceduralObject editedObject))
            {
                return;
            }

            if (m_ProceduralObjectToolSystem.IsMeshEditFaceSelectionActive)
            {
                FillFaceSelectionOutlineBuffer(ref buffer, editedObject);
                return;
            }

            MeshSelectionMode mode = m_ProceduralObjectToolSystem.MeshEditSelectionMode;
            if (mode != MeshSelectionMode.Edge && mode != MeshSelectionMode.SurfaceArea)
            {
                return;
            }

            // Edge mode draws the full structural wire for the active scope.
            // Surface mode reuses the same line buffer for region boundaries.
            if (mode == MeshSelectionMode.SurfaceArea)
            {
                FillSurfaceOutlineBuffer(ref buffer, editedObject);
                return;
            }

            // GPU Solid and X-Ray own their wires. Only the CPU fallback
            // populates ordinary edge lines here; operation outlines remain.
            if (suppressGpuEdgeWire)
            {
                return;
            }

            if (!m_ProceduralObjectToolSystem.TryGetMeshEditEdgeFrameData(out EdgeFrameData[] edgeFrames, out int edgeFrameCount, out uint _))
            {
                return;
            }

            // Rendering and picking consume the same scoped edge set. Solid
            // shares this interval mask directly; X-Ray keeps one visible
            // interval and projects it through the controller's native cache.
            for (int i = 0; i < edgeFrameCount; i++)
            {
                EdgeFrameData frame = edgeFrames[i];
                bool selected = m_ProceduralObjectToolSystem.IsMeshEditStructuralEdgeSelected(frame.Edge);
                bool hovered = m_ProceduralObjectToolSystem.IsMeshEditStructuralEdgeHovered(frame.Edge);

                Color color = selected && hovered ? s_EdgeSelectedHoveredColor : selected ? s_EdgeSelectedColor : hovered ? s_EdgeHoveredColor : s_EdgeNormalColor;

                AddVisibleEdgeSegments(ref buffer, frame, color);
            }
        }

        private void FillFaceSelectionOutlineBuffer(ref NativeList<StructuralEdgeRenderData> buffer, ProceduralObject editedObject)
        {
            if (!m_ProceduralObjectToolSystem.TryGetMeshEditFaceOperationRenderState(out ProceduralObject sourceObject, out int partIndex, out bool[] selectedFaces, out int hoveredFaceId, out uint _) || !ReferenceEquals(sourceObject, editedObject) || partIndex < 0 || partIndex >= editedObject.Parts.Count)
            {
                return;
            }

            MeshPart part = editedObject.Parts[partIndex];
            StructuralTopology topology = part.StructuralTopology;
            if (selectedFaces == null || selectedFaces.Length != topology.FaceCount)
            {
                return;
            }

            for (int edgeId = 0; edgeId < topology.StructuralEdgeCount; edgeId++)
            {
                StructuralEdge edge = topology.GetEdge(edgeId);
                int selectedAdjacentCount = 0;
                bool touchesHoveredFace = false;

                for (int i = 0; i < edge.AdjacentFaceCount; i++)
                {
                    int faceId = edge.AdjacentFaceIds[i];
                    if (faceId >= 0 && faceId < selectedFaces.Length && selectedFaces[faceId])
                    {
                        selectedAdjacentCount++;
                    }

                    touchesHoveredFace |= faceId == hoveredFaceId;
                }

                bool selectedBoundary = selectedAdjacentCount > 0 && selectedAdjacentCount < Math.Max(2, edge.AdjacentFaceCount);
                if (!selectedBoundary && !touchesHoveredFace)
                {
                    continue;
                }

                bool hoveredFaceSelected = hoveredFaceId >= 0 && hoveredFaceId < selectedFaces.Length && selectedFaces[hoveredFaceId];
                Color color = selectedBoundary && touchesHoveredFace ? s_EdgeSelectedHoveredColor : selectedBoundary ? s_EdgeSelectedColor : hoveredFaceSelected ? s_EdgeSelectedHoveredColor : s_EdgeHoveredColor;

                Vertex logicalA = part.Topology.GetVertex(edge.LogicalVertexA);
                Vertex logicalB = part.Topology.GetVertex(edge.LogicalVertexB);
                AddLine(ref buffer, editedObject.Transform.TransformPoint(logicalA.GetPosition(part.Mesh)), editedObject.Transform.TransformPoint(logicalB.GetPosition(part.Mesh)), color);
            }
        }

        private static void AddVisibleEdgeSegments(ref NativeList<StructuralEdgeRenderData> buffer, EdgeFrameData frame, Color color)
        {
            int intervalCount = frame.VisibleIntervalCount;
            uint visibleMask = frame.VisibleIntervalMask;

            if (intervalCount <= 0 || visibleMask == 0u)
            {
                return;
            }

            int intervalIndex = 0;
            while (intervalIndex < intervalCount)
            {
                if ((visibleMask & (1u << intervalIndex)) == 0u)
                {
                    intervalIndex++;
                    continue;
                }

                int visibleStart = intervalIndex;
                intervalIndex++;

                // Merge neighboring visible samples back into one overlay line.
                // X-Ray is represented as one interval, so it naturally keeps
                // the exact K1/K2 whole-edge rendering path.
                while (intervalIndex < intervalCount && (visibleMask & (1u << intervalIndex)) != 0u)
                {
                    intervalIndex++;
                }

                float startT = visibleStart / (float)intervalCount;
                float endT = intervalIndex / (float)intervalCount;

                AddLine(ref buffer, Vector3.Lerp(frame.WorldStart, frame.WorldEnd, startT), Vector3.Lerp(frame.WorldStart, frame.WorldEnd, endT), color);
            }
        }

        private void FillSurfaceOutlineBuffer(ref NativeList<StructuralEdgeRenderData> buffer, ProceduralObject editedObject)
        {
            int partIndex = m_ProceduralObjectSystem.SelectedPartIndex;
            if (partIndex < 0 || partIndex >= editedObject.Parts.Count)
            {
                return;
            }

            MeshPart part = editedObject.Parts[partIndex];
            int triangleCountTotal = part.Mesh.Triangles.Length / 3;
            bool[] selectedTriangles = new bool[triangleCountTotal];
            bool anySelected = false;
            bool hoveredSelection = false;

            for (int triangleId = 0; triangleId < triangleCountTotal; triangleId++)
            {
                SurfaceRef surface = new SurfaceRef(partIndex, triangleId);
                bool selected = m_ProceduralObjectToolSystem.IsMeshEditSurfaceSelected(surface);
                selectedTriangles[triangleId] = selected;
                anySelected |= selected;
                hoveredSelection |= selected && m_ProceduralObjectToolSystem.IsMeshEditSurfaceHovered(surface);
            }

            // A selection can mix Surface Areas and individual faces. Keep hovered areas
            // grouped only when none of their triangles are selected, allowing Alt drill-down.
            if (anySelected)
            {
                int selectedHoverTriangleId = FindHoveredSurfaceTriangle(partIndex, triangleCountTotal);
                if (selectedHoverTriangleId >= 0 && !selectedTriangles[selectedHoverTriangleId])
                {
                    int selectedHoverAreaId = part.GetTriangleSurfaceAreaId(selectedHoverTriangleId);
                    bool hoverWholeCustomArea = selectedHoverAreaId > MeshPart.kDefaultSurfaceAreaId && !HasSelectedTriangleInSurfaceArea(part, selectedHoverAreaId, selectedTriangles);

                    if (hoverWholeCustomArea)
                    {
                        bool[] hoveredAreaTriangles = new bool[triangleCountTotal];
                        FillSurfaceAreaTriangleMask(part, selectedHoverAreaId, hoveredAreaTriangles);
                        FillSurfaceRegionBoundary(ref buffer, editedObject, part, hoveredAreaTriangles, s_EdgeHoveredColor);
                    }
                    else
                    {
                        FillUnselectedSurfaceHoverOutlines(ref buffer, editedObject, partIndex, part, selectedTriangles);
                    }
                }

                Color selectedColor = hoveredSelection ? s_EdgeSelectedHoveredColor : s_EdgeSelectedColor;
                FillSurfaceRegionBoundary(ref buffer, editedObject, part, selectedTriangles, selectedColor);
                return;
            }

            int activeAreaId = m_ProceduralObjectSystem.SelectedSurfaceAreaId;
            bool hasActiveCustomArea = activeAreaId > MeshPart.kDefaultSurfaceAreaId;
            int hoveredTriangleId = FindHoveredSurfaceTriangle(partIndex, triangleCountTotal);
            int hoveredAreaId = hoveredTriangleId >= 0 ? part.GetTriangleSurfaceAreaId(hoveredTriangleId) : MeshPart.kDefaultSurfaceAreaId;
            bool hasHoveredCustomArea = hoveredTriangleId >= 0 && hoveredAreaId > MeshPart.kDefaultSurfaceAreaId;

            bool[] activeAreaTriangles = null;
            if (hasActiveCustomArea)
            {
                activeAreaTriangles = new bool[triangleCountTotal];
                FillSurfaceAreaTriangleMask(part, activeAreaId, activeAreaTriangles);

                Color activeColor = hasHoveredCustomArea && hoveredAreaId == activeAreaId ? s_EdgeSelectedHoveredColor : s_EdgeSelectedColor;
                FillSurfaceRegionBoundary(ref buffer, editedObject, part, activeAreaTriangles, activeColor);
            }

            if (hasHoveredCustomArea && hoveredAreaId != activeAreaId)
            {
                bool[] hoveredAreaTriangles = new bool[triangleCountTotal];
                FillSurfaceAreaTriangleMask(part, hoveredAreaId, hoveredAreaTriangles);
                FillSurfaceRegionBoundary(ref buffer, editedObject, part, hoveredAreaTriangles, s_EdgeHoveredColor);
                return;
            }

            if (hoveredTriangleId >= 0 && !hasHoveredCustomArea)
            {
                bool[] noSelectedTriangles = new bool[triangleCountTotal];
                FillUnselectedSurfaceHoverOutlines(ref buffer, editedObject, partIndex, part, noSelectedTriangles);
            }
        }

        private void FillSurfaceRegionBoundary(ref NativeList<StructuralEdgeRenderData> buffer, ProceduralObject editedObject, MeshPart part, bool[] includedTriangles, Color color)
        {
            // Count canonical logical edges across included faces. Interior
            // edges appear twice; only single-use edges belong to the outline.
            Dictionary<SurfaceBoundaryEdgeKey, int> edgeUseCounts = new Dictionary<SurfaceBoundaryEdgeKey, int>();
            StructuralTopology structuralTopology = part.StructuralTopology;

            for (int faceId = 0; faceId < structuralTopology.FaceCount; faceId++)
            {
                if (!part.TryGetStructuralFaceTriangles(faceId, out StructuralFaceTriangles faceTriangles))
                {
                    continue;
                }

                bool included = false;
                for (int i = 0; i < faceTriangles.Count; i++)
                {
                    int triangleId = faceTriangles[i];
                    if (triangleId >= 0 && triangleId < includedTriangles.Length && includedTriangles[triangleId])
                    {
                        included = true;
                        break;
                    }
                }

                if (!included)
                {
                    continue;
                }

                StructuralFace face = structuralTopology.GetFace(faceId);
                for (int corner = 0; corner < face.CornerCount; corner++)
                {
                    int next = (corner + 1) % face.CornerCount;
                    int renderA = face.GetRenderVertexIndex(corner);
                    int renderB = face.GetRenderVertexIndex(next);
                    AddSurfaceBoundaryEdgeUse(edgeUseCounts, part.Topology.GetLogicalVertexIdForRenderVertex(renderA), part.Topology.GetLogicalVertexIdForRenderVertex(renderB));
                }
            }

            // Imported/non-structural triangles still need an outline, so fold
            // their raw triangle edges into the same logical edge count.
            int[] triangles = part.Mesh.Triangles;
            for (int triangleId = 0; triangleId < includedTriangles.Length; triangleId++)
            {
                if (!includedTriangles[triangleId] || part.TryGetTriangleStructuralFaceId(triangleId, out int _))
                {
                    continue;
                }

                int offset = triangleId * 3;
                for (int edge = 0; edge < 3; edge++)
                {
                    int renderA = triangles[offset + edge];
                    int renderB = triangles[offset + ((edge + 1) % 3)];
                    AddSurfaceBoundaryEdgeUse(edgeUseCounts, part.Topology.GetLogicalVertexIdForRenderVertex(renderA), part.Topology.GetLogicalVertexIdForRenderVertex(renderB));
                }
            }

            foreach (KeyValuePair<SurfaceBoundaryEdgeKey, int> entry in edgeUseCounts)
            {
                if (entry.Value != 1)
                {
                    continue;
                }

                Vertex logicalA = part.Topology.GetVertex(entry.Key.LogicalVertexA);
                Vertex logicalB = part.Topology.GetVertex(entry.Key.LogicalVertexB);
                Vector3 worldA = editedObject.Transform.TransformPoint(logicalA.GetPosition(part.Mesh));
                Vector3 worldB = editedObject.Transform.TransformPoint(logicalB.GetPosition(part.Mesh));
                AddLine(ref buffer, worldA, worldB, color);
            }
        }

        private static void FillSurfaceAreaTriangleMask(MeshPart part, int surfaceAreaId, bool[] includedTriangles)
        {
            for (int triangleId = 0; triangleId < includedTriangles.Length; triangleId++)
            {
                includedTriangles[triangleId] = part.GetTriangleSurfaceAreaId(triangleId) == surfaceAreaId;
            }
        }

        private static bool HasSelectedTriangleInSurfaceArea(MeshPart part, int surfaceAreaId, bool[] selectedTriangles)
        {
            for (int triangleId = 0; triangleId < selectedTriangles.Length; triangleId++)
            {
                if (selectedTriangles[triangleId] && part.GetTriangleSurfaceAreaId(triangleId) == surfaceAreaId)
                {
                    return true;
                }
            }

            return false;
        }

        private int FindHoveredSurfaceTriangle(int partIndex, int triangleCount)
        {
            for (int triangleId = 0; triangleId < triangleCount; triangleId++)
            {
                if (m_ProceduralObjectToolSystem.IsMeshEditSurfaceHovered(new SurfaceRef(partIndex, triangleId)))
                {
                    return triangleId;
                }
            }

            return -1;
        }

        private void FillUnselectedSurfaceHoverOutlines(ref NativeList<StructuralEdgeRenderData> buffer, ProceduralObject editedObject, int partIndex, MeshPart part, bool[] selectedTriangles)
        {
            for (int faceId = 0; faceId < part.StructuralTopology.FaceCount; faceId++)
            {
                if (!part.TryGetStructuralFaceTriangles(faceId, out StructuralFaceTriangles faceTriangles))
                {
                    continue;
                }

                bool selected = false;
                bool hovered = false;
                for (int i = 0; i < faceTriangles.Count; i++)
                {
                    int triangleId = faceTriangles[i];
                    if (triangleId < 0 || triangleId >= selectedTriangles.Length)
                    {
                        continue;
                    }

                    selected |= selectedTriangles[triangleId];
                    hovered |= m_ProceduralObjectToolSystem.IsMeshEditSurfaceHovered(new SurfaceRef(partIndex, triangleId));
                }

                if (selected || !hovered)
                {
                    continue;
                }

                StructuralFace face = part.StructuralTopology.GetFace(faceId);
                for (int corner = 0; corner < face.CornerCount; corner++)
                {
                    int next = (corner + 1) % face.CornerCount;
                    Vector3 worldA = editedObject.Transform.TransformPoint(part.Mesh.Vertices[face.GetRenderVertexIndex(corner)]);
                    Vector3 worldB = editedObject.Transform.TransformPoint(part.Mesh.Vertices[face.GetRenderVertexIndex(next)]);
                    AddLine(ref buffer, worldA, worldB, s_EdgeHoveredColor);
                }
            }

            int[] triangles = part.Mesh.Triangles;
            for (int triangleId = 0; triangleId < selectedTriangles.Length; triangleId++)
            {
                if (selectedTriangles[triangleId] || part.TryGetTriangleStructuralFaceId(triangleId, out int _))
                {
                    continue;
                }

                SurfaceRef surface = new SurfaceRef(partIndex, triangleId);
                if (!m_ProceduralObjectToolSystem.IsMeshEditSurfaceHovered(surface))
                {
                    continue;
                }

                int offset = triangleId * 3;
                for (int edge = 0; edge < 3; edge++)
                {
                    int a = triangles[offset + edge];
                    int b = triangles[offset + ((edge + 1) % 3)];
                    AddLine(ref buffer, editedObject.Transform.TransformPoint(part.Mesh.Vertices[a]), editedObject.Transform.TransformPoint(part.Mesh.Vertices[b]), s_EdgeHoveredColor);
                }
            }
        }

        private static void AddSurfaceBoundaryEdgeUse(Dictionary<SurfaceBoundaryEdgeKey, int> edgeUseCounts, int logicalVertexA, int logicalVertexB)
        {
            if (logicalVertexA == logicalVertexB)
            {
                return;
            }

            SurfaceBoundaryEdgeKey key = new SurfaceBoundaryEdgeKey(logicalVertexA, logicalVertexB);
            if (edgeUseCounts.TryGetValue(key, out int count))
            {
                edgeUseCounts[key] = count + 1;
            }
            else
            {
                edgeUseCounts.Add(key, 1);
            }
        }

        private readonly struct SurfaceBoundaryEdgeKey : IEquatable<SurfaceBoundaryEdgeKey>
        {
            public int LogicalVertexA { get; }
            public int LogicalVertexB { get; }

            public SurfaceBoundaryEdgeKey(int logicalVertexA, int logicalVertexB)
            {
                LogicalVertexA = Math.Min(logicalVertexA, logicalVertexB);
                LogicalVertexB = Math.Max(logicalVertexA, logicalVertexB);
            }

            public bool Equals(SurfaceBoundaryEdgeKey other)
            {
                return LogicalVertexA == other.LogicalVertexA && LogicalVertexB == other.LogicalVertexB;
            }

            public override bool Equals(object obj)
            {
                return obj is SurfaceBoundaryEdgeKey other && Equals(other);
            }

            public override int GetHashCode()
            {
                unchecked
                {
                    return (LogicalVertexA * 397) ^ LogicalVertexB;
                }
            }
        }

        private static void AddLine(ref NativeList<StructuralEdgeRenderData> buffer, Vector3 start, Vector3 end, Color color)
        {
            buffer.Add(new StructuralEdgeRenderData
            {
                Start = start,
                End = end,
                Color = new float4(color.r, color.g, color.b, color.a),
            });
        }

