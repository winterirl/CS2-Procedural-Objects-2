    // Coordinates all mesh-edit visuals. Vertex rings and X-Ray edges prefer
    // indirect GPU renderers; GizmoBatcher remains their fallback and still
    // owns Solid edges, surface outlines, slide, and cut-preview lines.
    public partial class VertexRenderSystem : GameSystemBase
    {
        private struct VertexMarkerRenderData
        {
            public float3 Position;
            public float Radius;
            public float4 Color;
        }

        private struct LoopCutPreviewLineRenderData
        {
            public float3 Start;
            public float3 End;
            public float4 Color;
        }

        private struct StructuralEdgeRenderData
        {
            public float3 Start;
            public float3 End;
            public float4 Color;
        }

        private struct RenderMeshEditGizmosJob : IJob
        {
            public GizmoBatcher Batcher;

            public bool DrawSlideEdge;
            public float3 SlideEdgeStart;
            public float3 SlideEdgeEnd;

            [ReadOnly] public NativeArray<LoopCutPreviewLineRenderData> LoopCutPreviewLines;

            [ReadOnly] public NativeArray<StructuralEdgeRenderData> StructuralEdges;

            public void Execute()
            {
                // Ordinary structural edges are the baseline mesh-edit wire.
                // Temporary operation feedback draws afterward so cut/slide
                // targets stay visually dominant when they share an edge.
                for (int i = 0; i < StructuralEdges.Length; i++)
                {
                    StructuralEdgeRenderData line = StructuralEdges[i];
                    Batcher.DrawLine(line.Start, line.End, new Color(line.Color.x, line.Color.y, line.Color.z, line.Color.w));
                }

                for (int i = 0; i < LoopCutPreviewLines.Length; i++)
                {
                    LoopCutPreviewLineRenderData line = LoopCutPreviewLines[i];
                    Batcher.DrawLine(line.Start, line.End, new Color(line.Color.x, line.Color.y, line.Color.z, line.Color.w));
                }

                if (DrawSlideEdge)
                {
                    Batcher.DrawLine(SlideEdgeStart, SlideEdgeEnd, s_SlideTargetColor);
                }
            }
        }

        private struct RenderVertexMarkersJob : IJob
        {
            public GizmoBatcher Batcher;
            public float3 CameraForward;
            public float3 CameraRight;

            [ReadOnly] public NativeArray<VertexMarkerRenderData> Markers;

            public void Execute()
            {
                for (int i = 0; i < Markers.Length; i++)
                {
                    VertexMarkerRenderData marker = Markers[i];

                    // A low-segment camera-facing ring keeps vertex markers
                    // readable without the multiple full arcs generated by
                    // DrawWireSphere on very large converted meshes.
                    Batcher.DrawWireArc(marker.Position, CameraForward, CameraRight, 360f, marker.Radius, new Color(marker.Color.x, marker.Color.y, marker.Color.z, marker.Color.w), kMarkerArcPointCount);
                }
            }
        }

        // DrawWireArc includes both endpoints for a full 360-degree arc, so
        // nine points produce eight visible line segments.
        private const int kMarkerArcPointCount = 9;

        private static readonly Color s_SlideTargetColor = new Color(0.55f, 1f, 0.45f, 1f);

        private static readonly Color s_LoopCutPreviewColor = new Color(0.30f, 0.90f, 1f, 1f);

        private static readonly Color s_LoopCutTargetEdgeColor = new Color(1f, 0.80f, 0.20f, 1f);

        internal static readonly Color s_EdgeNormalColor = new Color(0.82f, 0.82f, 0.82f, 0.85f);

        internal static readonly Color s_EdgeHoveredColor = new Color(1f, 0.96f, 0.68f, 1f);

        internal static readonly Color s_EdgeSelectedColor = new Color(1f, 0.58f, 0.10f, 1f);

        internal static readonly Color s_EdgeSelectedHoveredColor = new Color(1f, 0.82f, 0.30f, 1f);

