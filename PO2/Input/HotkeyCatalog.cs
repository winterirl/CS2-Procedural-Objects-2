    internal readonly struct HotkeyDefinition
    {
        internal readonly string Name, Group;
        internal readonly HotkeyScope Scope;
        internal readonly bool HasSettingsEntry;
        internal string LabelKey => "PO2.Settings.Hotkeys.Action." + Name;
        internal string DescriptionKey => "PO2.Settings.Hotkeys.Description." + Name;
        internal string GroupKey => "PO2.Settings.Hotkeys.Group." + Group;

        internal HotkeyDefinition(string name, string group, HotkeyScope scope, bool hasSettingsEntry = true)
        {
            Name = name;
            Group = group;
            Scope = scope;
            HasSettingsEntry = hasSettingsEntry;
        }
    }

